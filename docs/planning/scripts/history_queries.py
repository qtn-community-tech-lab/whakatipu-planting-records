#!/usr/bin/env python3
"""
history_queries.py  -  S7 (Phase 2): the questions WRT staff ask of the planting history,
answered from the clean table alone (no workbook is opened).

Reads   planning/prototype/planting_history.csv, site_crosswalk.csv, species_master_proposed.csv,
        history_reconciliation.csv   (all made by build_history_prototype.py)
Writes  planning/prototype/history_queries_output.md

Each answer shows how much of it rests on rows flagged needs_review, so a number is never
presented as cleaner than it is.  Names are looked up, not typed as IDs: "Whitechapel" finds the
site through site_crosswalk.csv, "manuka" finds the species through the master list's common name.

Run:  python3 history_queries.py
"""
import csv
from collections import defaultdict
from pathlib import Path

P = Path("/home/claude/planning/prototype")
OUT = P / "history_queries_output.md"


def read(name):
    with open(P / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


hist = read("planting_history.csv")
for r in hist:
    r["qty"] = int(r["quantity"]) if r["quantity"] != "" else None
    r["year"] = int(r["year"])
sites = read("site_crosswalk.csv")
species = read("species_master_proposed.csv")
recon = read("history_reconciliation.csv")

site_name = {}
for s in sites:
    site_name.setdefault(s["site_id_proposed"], s["site_name_proposed"])


def n(x):
    return f"{x:,}"


def table(headers, rows, align=None):
    align = align or ["l"] + ["r"] * (len(headers) - 1)
    sep = ["---:" if a == "r" else "---" for a in align]
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(sep) + " |"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def flagged(rows):
    f = [r for r in rows if r["needs_review"] == "Y" and r["qty"] is not None]
    return len(f), sum(r["qty"] for r in f)


def flag_line(rows):
    k, p = flagged(rows)
    tot = sum(r["qty"] for r in rows if r["qty"] is not None)
    return (f"Rows resting on a flagged record: {k} of {len(rows)} ({n(p)} of {n(tot)} plants). "
            f"Flags are listed in `review_reason`; filter `needs_review = N` to see the unflagged part.")


def season_key(r):
    return (r["year"], r["season"] != "Autumn")


md = []
md.append("# History queries: answers from the clean planting table\n")
md.append("Generated by `scripts/history_queries.py` from `prototype/planting_history.csv` "
          f"({n(len(hist))} rows). Nothing here opens a workbook. Quantities are *as recorded in the workbook "
          "matrix*: whether they were planted or only allocated is still WRT decision 3, and the two 2024 Slope Hill "
          "columns (decision 4) are included and flagged. Sites and species are *proposed* mappings; rows needing a ruling "
          "carry `needs_review = Y`.\n")

# ------------------------------------------------------------------ (a)
site_q = "whitechapel"
ids = sorted({sid for sid, nm in site_name.items() if site_q in nm.lower() and sid})
md.append("## (a) What did we plant at Whitechapel in 2019?\n")
md.append(f"Lookup: the name \"Whitechapel\" resolves through `site_crosswalk.csv` to site ID {', '.join(ids)}. "
          "Nobody types the ID; the 2019 headers read `Whitechapel  ` with two trailing spaces.\n")
rows_a = [r for r in hist if r["site_id_proposed"] in ids and r["year"] == 2019 and r["qty"] is not None]
by_sp = defaultdict(lambda: {"Autumn": 0, "Spring": 0})
for r in rows_a:
    by_sp[r["species_canonical"]][r["season"]] += r["qty"]
tbl = [(sp, v["Autumn"] or "", v["Spring"] or "", v["Autumn"] + v["Spring"]) for sp, v in sorted(by_sp.items(), key=lambda kv: -(kv[1]["Autumn"] + kv[1]["Spring"]))]
tot_a = sum(r["qty"] for r in rows_a)
tbl.append(("**Total**", n(sum(r["qty"] for r in rows_a if r["season"] == "Autumn")), n(sum(r["qty"] for r in rows_a if r["season"] == "Spring")), f"**{n(tot_a)}**"))
md.append(table(["Species", "Autumn 2019", "Spring 2019", "Total"], [(a, b if isinstance(b, str) else (n(b) if b != "" else ""), c if isinstance(c, str) else (n(c) if c != "" else ""), d if isinstance(d, str) else n(d)) for a, b, c, d in tbl]))
md.append(f"\n{len(by_sp)} species, {len(rows_a)} rows. Source cells are in `MASTER` column {' and '.join(sorted({r['source_cell'].rstrip('0123456789') for r in rows_a}))} (Autumn first, then Spring). {flag_line(rows_a)}\n")

# ------------------------------------------------------------------ (b)
md.append("## (b) How many plants have gone into Whitechapel, year by year?\n")
rows_b = [r for r in hist if r["site_id_proposed"] in ids and r["qty"] is not None]
yr = defaultdict(lambda: {"Autumn": 0, "Spring": 0, "rows": 0, "sp": set()})
for r in rows_b:
    yr[r["year"]][r["season"]] += r["qty"]
    yr[r["year"]]["rows"] += 1
    yr[r["year"]]["sp"].add(r["species_id_proposed"])
cum = 0
tb = []
for y in sorted(yr):
    t = yr[y]["Autumn"] + yr[y]["Spring"]
    cum += t
    tb.append((y, n(yr[y]["Autumn"]) if yr[y]["Autumn"] else "-", n(yr[y]["Spring"]) if yr[y]["Spring"] else "-", n(t), n(cum), len(yr[y]["sp"]), yr[y]["rows"]))
md.append(table(["Year", "Autumn", "Spring", "Year total", "Running total", "Species", "Rows"], tb))
md.append(f"\nAll years: {n(cum)} plants in {len(rows_b)} rows. Autumn 2015 is the column headed `WCR` (old site number 4, which the register maps to 15). "
          "A dash means no Whitechapel rows that season: MASTER has no Spring 2015 Whitechapel column, and Spring 2026 is not in it yet. " + flag_line(rows_b) + "\n")

# ------------------------------------------------------------------ (c)
q = "manuka"
hit = [s for s in species if q in (s["common_name"] + " " + s["maori_name"]).lower().replace("ā", "a")]
sp_ids = sorted({s["species_id"] for s in hit})
md.append("## (c) How many mānuka have we planted, and when?\n")
md.append(f"Lookup: \"mānuka\" matches the common or Māori name of {', '.join(sp_ids)} "
          f"({', '.join(sorted({s['canonical_handle'] for s in hit}))}) in `species_master_proposed.csv`. The workbook itself only ever says the Latin name.\n")
rows_c = [r for r in hist if r["species_id_proposed"] in sp_ids and r["qty"] is not None]
yc = defaultdict(lambda: {"Autumn": 0, "Spring": 0, "sites": set(), "rows": 0})
for r in rows_c:
    yc[r["year"]][r["season"]] += r["qty"]
    yc[r["year"]]["rows"] += 1
    if r["site_id_proposed"]:
        yc[r["year"]]["sites"].add(r["site_id_proposed"])
    else:
        yc[r["year"]]["sites"].add("scheme:" + r["site_original"])
cum = 0
tb = []
for y in sorted(yc):
    t = yc[y]["Autumn"] + yc[y]["Spring"]
    cum += t
    tb.append((y, n(yc[y]["Autumn"]) if yc[y]["Autumn"] else "-", n(yc[y]["Spring"]) if yc[y]["Spring"] else "-", n(t), n(cum), len(yc[y]["sites"])))
md.append(table(["Year", "Autumn", "Spring", "Year total", "Running total", "Site columns (distinct)"], tb))
top = defaultdict(int)
for r in rows_c:
    top[(r["site_id_proposed"] or "scheme", r["site_group_proposed"])] += r["qty"]
best = sorted(top.items(), key=lambda kv: -kv[1])[:5]
md.append(f"\nAll years: **{n(cum)}** plants in {len(rows_c)} rows. Largest five site groups by mānuka: "
          + "; ".join(f"{g} ({n(v)})" for (_, g), v in best) + ". " + flag_line(rows_c) + "\n")

# ------------------------------------------------------------------ (d)
md.append("## (d) Planting totals by season, all 23 blocks\n")
bs = defaultdict(lambda: {"plants": 0, "rows": 0, "sites": set(), "flag": 0})
for r in hist:
    if r["qty"] is None:
        continue
    k = (r["year"], r["season"])
    bs[k]["plants"] += r["qty"]
    bs[k]["rows"] += 1
    bs[k]["sites"].add((r["site_original"], r["source_cell"].rstrip("0123456789")))
    if r["needs_review"] == "Y":
        bs[k]["flag"] += r["qty"]
stated = {x["label"]: int(x["stated"]) for x in recon if x["item"] == "season"}
tb = []
tot = tot_f = 0
for (y, s) in sorted(bs, key=lambda k: (k[0], k[1] != "Autumn")):
    d = bs[(y, s)]
    lab = f"{s} {y}"
    st = stated.get(lab)
    tot += d["plants"]
    tot_f += d["flag"]
    tb.append((lab, len(d["sites"]), n(d["rows"]), n(d["plants"]), n(st) if st is not None else "n/a", d["plants"] - st if st is not None else "n/a", n(d["flag"])))
tb.append(("**All 23**", "", n(sum(d["rows"] for d in bs.values())), f"**{n(tot)}**", n(sum(stated.values())), tot - sum(stated.values()), n(tot_f)))
md.append(table(["Season", "Site columns with plants", "Rows", "Plants (from rows)", "MASTER TOTAL column", "Difference", "Plants on flagged rows"], tb))
pyx = [x for x in recon if x["label"].startswith("MASTER!PY107")][0]
md.append(f"\nEvery season equals its `TOTAL` column. The all-time figure is {n(tot)}, against `PY107` {n(int(pyx['stated']))}: "
          f"the difference of {tot - int(pyx['stated'])} is one cell (row 106, Spring 2025) outside the `PY107` sum range. "
          "Spring 2024 (29,826) and Autumn 2024 (13,657) are large because of the two Slope Hill columns (22,000 and 7,000), which decision 4 has yet to rule on.\n")

# ------------------------------------------------------------------ (e)
md.append("## (e) Which sites were planted in Autumn 2024?\n")
rows_e = [r for r in hist if r["year"] == 2024 and r["season"] == "Autumn" and r["qty"] is not None]
ge = defaultdict(lambda: {"plants": 0, "sp": set(), "rows": 0, "flag": 0, "id": "", "grp": "", "cls": "", "prec": set(), "orig": set()})
for r in rows_e:
    k = (r["site_id_proposed"], r["site_original"].strip())
    d = ge[k]
    d["plants"] += r["qty"]
    d["rows"] += 1
    d["sp"].add(r["species_id_proposed"])
    d["id"], d["grp"], d["cls"] = r["site_id_proposed"], r["site_group_proposed"], r["site_class"]
    d["prec"].add(r["precision"])
    if r["needs_review"] == "Y":
        d["flag"] += 1
tb = []
for (sid, orig), d in sorted(ge.items(), key=lambda kv: -kv[1]["plants"]):
    nm = site_name.get(sid, "") or orig
    tb.append((nm, sid or "none", d["grp"], d["cls"], "/".join(sorted(d["prec"])), len(d["sp"]), n(d["plants"]), f"{d['flag']} of {d['rows']}"))
md.append(table(["Site (proposed name)", "ID", "Group", "Class", "Precision", "Species", "Plants", "Flagged rows"], tb,
                ["l", "l", "l", "l", "l", "r", "r", "r"]))
md.append(f"\n{len(ge)} site columns, {n(sum(r['qty'] for r in rows_e))} plants, {len(rows_e)} rows. " + flag_line(rows_e) + "\n")

md.append("## How these were produced\n")
md.append("Five queries, each a filter and a sum over one table. In Google Sheets the same answers are a `QUERY` or pivot over a `Planting` tab "
          "with a site-name lookup; in a database they are `GROUP BY`. The point is that none needs an old workbook, a column letter or a species row number.\n")

OUT.write_text("\n".join(md), encoding="utf-8")
print("wrote", OUT)
